            const keysToKeepLast = ['id', 'name', 'email', 'mobile', 'type', 'group_member', 'created_by', 'assigned_to', 'country_option'];
            if (Array.isArray(searchTerm)) {
                keysToKeepLast.forEach(key => {
                    const itemsWithKey = searchTerm.filter(item => key in item);
                    if (itemsWithKey.length > 1) {
                        const lastItem = itemsWithKey[itemsWithKey.length - 1];
                        searchTerm.forEach(item => {
                            if (item !== lastItem) {
                                delete item[key];
                            }
                        });
                    }
                });
                searchTerm = searchTerm.filter(item => Object.keys(item).length !== 0);
            }
            $('#loader').show();
            $('#kanban-view').hide();
            setTimeout(function() {
                $('#loader').hide();
                $('#kanban-view').show();
