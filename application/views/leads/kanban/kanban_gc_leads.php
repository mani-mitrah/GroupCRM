                    const hasName = searchTerm.some(item => 'name' in item);
                    const hasEmail = searchTerm.some(item => 'email' in item);
                    const hasMobile = searchTerm.some(item => 'mobile' in item);
                    const hasType = searchTerm.some(item => 'type' in item);
                    const hasStatus = searchTerm.some(item => 'status' in item);
                    const hasCreatedGroup = searchTerm.some(item => 'created_group' in item);
                    const hasAssignedGroup = searchTerm.some(item => 'assigned_group' in item);
                    const hasCreated = searchTerm.some(item => 'created_by' in item);
                    const hasAssigned = searchTerm.some(item => 'assigned_to' in item);
                    const hasSLA = searchTerm.some(item => 'sla_group' in item);
                    const hasRTV = searchTerm.some(item => 'rtv_group' in item);
                    const hasCountry = searchTerm.some(item => 'country_option' in item);
                    var $cards = $columnBody.find('.kanban-card');

                    $cards.each(function() {
                        var $card = $(this);
                        var matches = true;
                        if (hasId) {
