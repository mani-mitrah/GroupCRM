                    if (checkedIds.includes('name') && !/^[a-zA-Z\s]+$/.test(name)) {
                        error += 'Name is required and must contain only letters.<br>';
                    }
                    if (checkedIds.includes('email') && !/^\S+@\S+\.\S+$/.test(email)) {
                        error += 'Enter a valid email.<br>';
                    }

                    if (checkedIds.includes('mobile') && isNaN(mobile)) {
                        error += 'Mobile must be a number.<br>';
                    }
                    if (error) {
                        $('#error').html(error);
                    } else {
                        $('#error').html('');
                        getFilterData(id, name, email, mobile, searchTerm)
                    }

                } else {
                    $('#error').html('Select the checked Fields and fill required fields');
                    setTimeout(function() {
                        $('#error').html('');
                        searchTerm.forEach(item => {
                            delete item.id;
                            delete item.name;
                            delete item.email;
                            delete item.mobile;
                        });
                        searchFilter(searchTerm, true);
                    }, 1500);
                }
            } else {
                let status = $('input[name="check_status"]:checked').val();
                searchTerm.forEach(item => delete item.status);
                searchTerm.push({
                    status: status
                });
                searchFilter(searchTerm, true);
            }
        };

        // Customer Info Filter
        function getFilterData(lead_id = null, lead_name = null, lead_email = null, lead_mobile = null, searchTerm) {
            if (lead_id !== null && lead_id !== '') searchTerm.push({
                id: lead_id
            });
            if (lead_name !== null && lead_name !== '') searchTerm.push({
                name: lead_name
            });
            if (lead_email !== null && lead_email !== '') searchTerm.push({
                email: lead_email
            });
            if (lead_mobile !== null && lead_mobile !== '') searchTerm.push({
                mobile: lead_mobile
            });
            searchFilter(searchTerm, true)
        }

        // clear status filter status
        $('#clearStatus').click(function() {
            $('input[name="check_status"]:checked').prop('checked', false);
            const foundItem = searchTerm.find(item => 'status' in item);
            if (foundItem) {
                delete foundItem.status;
            }
            searchFilter(searchTerm, true);
        });

        // Create Group and Assigned To filter
        $(document).on('change', '.check_group', function() {
            let checkedAGroup = $('input[name="assigned_groups[]"]:checked').map(function() {
                return $(this).val();
            }).get();

            let checkedCGroup = $('input[name="created_groups[]"]:checked').map(function() {
                return $(this).val();
            }).get();

            let checkedAIds = $('input[name="assigned_groups[]"]:checked').map(function() {
                return $(this).attr('id');
            }).get();

            let checkedCIds = $('input[name="created_groups[]"]:checked').map(function() {
                return $(this).attr('id');
            }).get();


            if (checkedAGroup.length > 0) {
                searchTerm.forEach(item => delete item.assigned_group);
                searchTerm.push({
                    assigned_group: checkedAGroup
                });
                searchFilter(searchTerm, true);
                getAssignedUser(checkedAIds, '#assigned_to');
            } else {
                searchTerm.forEach(item => delete item.assigned_group);
                $('#assigned_to').empty();
            }
            if (checkedCGroup.length > 0) {
                searchTerm.forEach(item => delete item.created_group);
                searchTerm.push({
                    created_group: checkedCGroup
                });
                searchTerm = searchTerm.filter(item => Object.keys(item).length !== 0);
                searchFilter(searchTerm, true);
                getAssignedUser(checkedCIds, '#created_by');
            } else {
                searchTerm.forEach(item => delete item.created_group);
                $('#created_by').empty();
            }
            if (checkedAGroup.length == 0 && checkedCGroup.length == 0) {
                searchTerm.forEach(item => delete item.created_group);
                searchTerm.forEach(item => delete item.assigned_group);
                searchFilter(searchTerm, true);
                $(".group_members").empty();
            }
        })

        // created Users filter
        $(".group_members").change(function() {
            let checkedValues = $('.check_member:checked').map(function() {
                return $(this).val();
            }).get();
            let checkedIds = $(this).attr('id');
            if (checkedValues.length > 0) {
                searchTerm.push({
                    [checkedIds]: checkedValues
                });
                searchFilter(searchTerm, true);
            } else {
                searchTerm.forEach(item => {
                    delete item[checkedIds];
                });
                searchFilter(searchTerm, true);
            }
        })

        $(".date_valid").change(function() {
            let id = $(this).attr('id');
            let value = $('#' + id + ':checked').val();
            if (value) {
                searchTerm.push({
                    [id]: true
                });
                searchFilter(searchTerm, true);
            } else {
                searchTerm.forEach(item => {
                    delete item[id];
                });
                searchFilter(searchTerm, true);
            }
        })

        window.close_drop = function(id) {
            $('#' + id + '_dropdown').hide();
        }

        window.openDD = function(type) {
            let id = type.replace('up', 'down');
            $('#' + id).show();
        };

        window.asc_desc = function(id) {
            let type = 'asc'
            if ($('#' + id + '_desc_order').hasClass('active')) {
                $('#' + id + '_desc_order').removeClass('active');
                $('#' + id + '_asc_order').addClass('active');
            } else {
                $('#' + id + '_asc_order').removeClass('active');
                $('#' + id + '_desc_order').addClass('active');
                type = 'desc';
            }
            let $columnBody = $('#' + id + ' .kanban-column-body');
            let sortedCards = $columnBody.find('.kanban-card').sort(function(a, b) {
                let dateA = new Date($(a).find('.date').val());
                let dateB = new Date($(b).find('.date').val());
                if (type == 'asc') {
                    return dateA - dateB;
                } else {
                    return dateB - dateA;
                }
            });
            $columnBody.html(sortedCards);
            $('#' + id + '_dropdown').hide();
        }
        window.export_leads = function(id) {
            let lead_ids = [];
            $('.' + id + '_ids').each(function() {
                lead_ids.push($(this).val());
            });
            if (lead_ids == '') {
                Swal.fire("Error", "You don't leads in this column", "error");
            } else {
                $('#lead_ids').val(lead_ids);
                $('#lead_type').val(id);
                $('#kanbanReportForm').submit();
            }
            $('.export_class').val('');
            $('#' + id + '_dropdown').hide();
        }
    });
