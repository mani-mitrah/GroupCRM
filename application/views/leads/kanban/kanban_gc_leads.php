                            var emailText = $card.find('.lead_email').text().toLowerCase().trim();
                            if (emailText.indexOf(foundItem.email) === -1) {
                                matches = false;
                            }
                        }

                        if (hasSLA) {
                            let sla = $card.find('.sla_date.bg-none').length;
                            if (sla <= 0) {
                                matches = false;
                            }
                        }

                        if (hasRTV) {
                            let rtv = $card.find('.rtv_date.bg-none').length;
                            if (rtv <= 0) {
                                matches = false;
                            }
                        }

                        if (hasMobile) {
                            var foundItem = searchTerm.find(item => 'mobile' in item);
                            var mobileText = $card.find('.lead_mobile').text().trim();
                            if (mobileText.indexOf(foundItem.mobile) === -1) {
                                matches = false;
                            }
                        }

                        if (hasType) {
                            var foundItem = searchTerm.find(item => 'type' in item);
